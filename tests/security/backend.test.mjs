test('real PostgreSQL authority, privacy, literal credentials, persistence and concurrency',async()=>{
  const suffix=key().slice(0,8);
  const alice=await createAccount({username:'alice-'+suffix,password,name:'Alice',color:'#b7394b'});
  const bob=await createAccount({username:'bob-'+suffix,password,name:'Bob',color:'#123456'});
  const a=cookies(alice.sessionToken),b=cookies(bob.sessionToken);
  assert.equal((await signIn({username:'alice-'+suffix,password})).user.id,alice.user.id);
  await rejected(signIn({username:"' OR 1=1 --",password}),401);
  await rejected(signIn({username:'alice-'+suffix,password:"' OR 1=1 --"}),401);
  await rejected(createAccount({username:'short-'+suffix,password:'short',name:'Short'}),400);
  await updateProfile(a,{name:"'; DROP TABLE dm_profiles; --"});
  assert.ok((await dbPool().query('select id from dm_profiles where id=$1',[alice.user.id])).rowCount);
  assert.equal(await readActor('dnd-dm-session='+alice.user.id),null);
  assert.equal((await dbPool().query('select token_hash from dm_sessions where profile_id=$1',[alice.user.id])).rows.every(row=>/^[a-f0-9]{64}$/.test(row.token_hash)&&row.token_hash!==alice.sessionToken),true);
  const metadata=await saveRoomMetadata(a,{name:'Security Room'}),code=metadata.roomCode;
  await rejected(readRoom('',code),401);
  await rejected(readRoom(b,code),403);
  await rejected(saveRoomMetadata(b,{id:metadata.id,name:'Hijacked'}),403);
  const first=await joinRoom('',code,{nickname:'Player One',color:'#ffffff'});
  const second=await joinRoom('',code,{nickname:'Player Two',color:'#ffffff'});
  const g1='dnd-guest-session='+first.sessionToken,g2='dnd-guest-session='+second.sessionToken;
  assert.notEqual(first.profile.id,second.profile.id);assert.notEqual(first.profile.color,second.profile.color);
  await rejected(joinRoom('',code,{id:alice.user.id,nickname:'Fake DM'}),400);
  const issue=(header,commands,extra={})=>roomCommand(header,code,{id:key(),commands,...extra});
  const dmToken='dm-token-'+suffix;
  await issue(a,[{type:'token.create',payload:{token:{id:dmToken,name:'Monster',icon:'M',type:'monster',x:0,y:0,size:1,hp:'SECRET HP',note:'SECRET DM NOTE'}}}]);
  let dmView=await readRoom(a,code),guestView=await readRoom(g1,code);
  assert.equal(dmView.tokens[0].hp,'SECRET HP');assert.equal(dmView.tokens[0].note,'SECRET DM NOTE');
  assert.equal('hp' in guestView.tokens[0],false);assert.equal('note' in guestView.tokens[0],false);assert.doesNotMatch(JSON.stringify(guestView),/SECRET/);
  await rejected(issue(g1,[{type:'token.update',payload:{id:dmToken,patch:{name:'Hacked'}}}]),403);
  await rejected(issue(g1,[{type:'grid.update',payload:{patch:{rows:30}}}]),403);
  await rejected(issue(g1,[{type:'combat.set',payload:{combat:dmView.combat}}]),403);
  await rejected(issue(g1,[{type:'token.assign',payload:{id:dmToken,ownerId:first.profile.id}}]),403);
  await issue(a,[{type:'dice.roll',payload:{expression:'d20',private:true}}]);
  assert.equal((await readRoom(g1,code)).rolls.length,0);
  await issue(g1,[{type:'dice.roll',payload:{expression:'2d6+3',private:true}}]);
  assert.equal((await readRoom(g1,code)).rolls.length,1);assert.equal((await readRoom(g2,code)).rolls.length,0);assert.equal((await readRoom(a,code)).rolls.length,2);
  await issue(a,[{type:'token.assign',payload:{id:dmToken,ownerId:first.profile.id}}]);
  guestView=await readRoom(g1,code);assert.equal(guestView.tokens[0].hp,'SECRET HP');assert.equal(guestView.tokens[0].note,undefined);
  assert.equal((await readRoom(g2,code)).tokens[0].hp,undefined);
  await issue(g1,[{type:'token.update',payload:{id:dmToken,patch:{name:'Assigned monster',note:'Public player note',x:2}}}]);
  assert.equal((await readRoom(a,code)).tokens[0].note,'SECRET DM NOTE');
  await rejected(issue(g1,[{type:'token.update',payload:{id:dmToken,patch:{ownerId:second.profile.id}}}]),400);
  const own='own-'+suffix;
  await issue(g1,[{type:'token.create',payload:{token:{id:own,name:'Hero',type:'character',ownerId:alice.user.id}}}]);
  assert.equal((await readRoom(g1,code)).tokens.find(t=>t.id===own).ownerId,first.profile.id);
  await issue(g1,[{type:'initiative.add',payload:{id:'init-'+suffix,tokenId:own}}]);
  await issue(g1,[{type:'initiative.submit',payload:{id:'init-'+suffix,manualTotal:18}}]);
  await rejected(issue(g2,[{type:'initiative.submit',payload:{id:'init-'+suffix,manualTotal:99}}]),403);
  await rejected(issue(g1,[{type:'token.update',payload:{id:own,patch:{x:Infinity}}}]),400);
  await rejected(issue(g1,[{type:'room_patch',payload:{room:{}}}]),400);
  await issue(g1,[{type:'token.delete',payload:{id:own}}]);
  assert.equal((await readRoom(a,code)).combat.entries.some(e=>e.tokenId===own),false);
  const command={id:key(),commands:[{type:'dice.roll',payload:{expression:'d20',private:false}}]};
  const once=await roomCommand(a,code,command),twice=await roomCommand(a,code,command);assert.equal(twice.revision,once.revision);assert.equal(twice.rolls.length,once.rolls.length);
  const revision=twice.revision;
  const concurrent=await Promise.allSettled([issue(a,[{type:'grid.update',payload:{patch:{rows:25}}}],{revision}),issue(a,[{type:'grid.update',payload:{patch:{rows:26}}}],{revision})]);
  assert.equal(concurrent.filter(r=>r.status==='fulfilled').length,1);assert.equal(concurrent.find(r=>r.status==='rejected').reason.status,409);
  const preset=await saveLibrary(a,{kind:'token',name:'Owner preset',category:'Test',icon:'X',tokenType:'monster',size:1});
  await rejected(saveLibrary(b,{id:preset.id,kind:'token',name:'Hijacked',category:'Test',icon:'X',tokenType:'monster',size:1}),403);
  await rejected(saveLibrary(b,{kind:'token',name:'Forged',category:'Test',icon:'X',tokenType:'monster',size:1,createdBy:alice.user.id}),400);
  const before=await readRoom(a,code);await globalThis.dndPool.end();delete globalThis.dndPool;
  const recovered=await readRoom(a,code);assert.deepEqual(recovered,before);
  await dbPool().query('delete from dm_sessions where profile_id=$1',[alice.user.id]);await rejected(readRoom(a,code),401);
});

test('input validators reject script URLs, fake image data, oversized bodies and excess requests',async()=>{
  const previous=process.env.APP_URL;process.env.APP_URL='https://table.example.com';assert.equal(cookieOptions().secure,true);if(previous===undefined)delete process.env.APP_URL;else process.env.APP_URL=previous;
  assert.throws(()=>image('javascript:alert(1)'),ApiError);
  assert.throws(()=>image('data:image/png;base64,PHN2ZyBvbmxvYWQ9eD48L3N2Zz4='),ApiError);
  const id='test-rate-'+key();rateLimit(id,2);rateLimit(id,2);assert.throws(()=>rateLimit(id,2),error=>error.status===429);
  const invalid=new Request('http://localhost/',{method:'POST',body:'{invalid'});await assert.rejects(readJSON(invalid),error=>error.status===400);
  const oversized=new Request('http://localhost/',{method:'POST',headers:{'Content-Length':String(MAX_BODY+1)},body:'{}'});await assert.rejects(readJSON(oversized),error=>error.status===413);
});
